from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path
from decimal import Decimal, InvalidOperation


_DEC_0_1_RE = re.compile(r"^0\.(\d+)$")


def _parse_decimal_0_1_and_code(value: str) -> tuple[Decimal, str]:
    """
    Accepts decimals strictly in (0, 1) formatted as "0.<digits>".

    Code is generated by removing the dot only:
      0.055  -> "0055"
      0.0555 -> "00555"
      0.2    -> "02"
    """
    s = str(value).strip()
    if not s:
        raise ValueError("empty value")
    m = _DEC_0_1_RE.match(s)
    if not m:
        raise ValueError('value must look like "0.<digits>", e.g. "0.05"')
    frac = m.group(1)
    try:
        dec = Decimal(s)
    except InvalidOperation as e:
        raise ValueError(f"invalid decimal: {s}") from e
    if not (Decimal("0") < dec < Decimal("1")):
        raise ValueError(f"value must be in (0, 1), got {s}")
    code = "0" + frac
    return dec, code


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run Axis 3 fixed-budget training (wrapper around scripts/train.py)."
    )
    parser.add_argument(
        "budget",
        help='Budget as a decimal in (0, 1), e.g. "0.05".',
    )
    parser.add_argument("--seed", type=int, default=42, help="Experiment seed.")
    parser.add_argument(
        "--timesteps",
        type=int,
        default=300000,
        help="Total training timesteps.",
    )
    parser.add_argument(
        "--save-every",
        type=int,
        default=50000,
        help="Checkpoint frequency in steps.",
    )
    parser.add_argument(
        "--python",
        default="/tmp2/b14902068/.venv/bin/python",
        help="Python executable to run training (default matches ws7 venv).",
    )
    parser.add_argument(
        "--config",
        default="configs/research_v1/axis3_budget_fixed_default_final.yaml",
        help="Base YAML config path.",
    )
    parser.add_argument(
        "--runs-root",
        default="runs/research_v1",
        help="Root output directory for runs.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the command and exit without running it.",
    )
    args, extra_overrides = parser.parse_known_args()

    budget_dec, budget_code = _parse_decimal_0_1_and_code(args.budget)
    name = f"axis3_fixed{budget_code}_s{args.seed}"
    out_dir = str(Path(args.runs_root) / name)

    cmd = [
        args.python,
        "scripts/train.py",
        "--config",
        args.config,
        f"experiment.name={name}",
        f"experiment.output_dir={out_dir}",
        f"training.total_timesteps={int(args.timesteps)}",
        f"training.save_every_steps={int(args.save_every)}",
        "safety_budget.mode=fixed",
        f"safety_budget.budget={budget_dec}",
        f"experiment.seed={int(args.seed)}",
        *extra_overrides,
    ]

    # Helpful echo for logs / tmux.
    print(" ".join(cmd), flush=True)
    if args.dry_run:
        return 0

    # Run in repo root (parent of scripts/).
    repo_root = Path(__file__).resolve().parents[1]
    proc = subprocess.run(cmd, cwd=str(repo_root))
    return int(proc.returncode)


if __name__ == "__main__":
    raise SystemExit(main())
